#!/usr/bin/env node
// Generates design/tokens/volve.css from design/tokens/volve.tokens.json.
// Run after any token edit: node design/scripts/build-tokens.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const tokens = JSON.parse(fs.readFileSync(path.join(root, 'tokens', 'volve.tokens.json'), 'utf8'));

const v = (node) => node.$value;
const lines = [];
const add = (name, value) => lines.push(`  --${name}: ${value};`);

for (const [name, node] of Object.entries(tokens.color)) if (node.$value) add(name, v(node));

const alpha = {
  'text-secondary-on-dark': 'rgba(249, 246, 241, 0.75)',
  'line-on-light': 'rgba(28, 20, 16, 0.12)',
  'line-on-white': 'rgba(28, 20, 16, 0.12)',
  'line-on-dark': 'rgba(249, 246, 241, 0.16)',
  'fill-subtle': 'rgba(28, 20, 16, 0.06)',
  'gold-wash': v(tokens.tint['gold-wash']),
  'alert-wash': v(tokens.tint['alert-wash']),
};
for (const [name, value] of Object.entries(alpha)) add(name, value);

add('font-display', v(tokens.font.display));
add('font-sans', v(tokens.font.sans));
for (const [k, node] of Object.entries(tokens.space)) if (node.$value) add(`space-${k}`, v(node));
for (const [k, node] of Object.entries(tokens.radius)) if (node.$value) add(`radius-${k}`, v(node));
for (const [k, node] of Object.entries(tokens.shadow)) add(`shadow-${k}`, v(node));
for (const [k, node] of Object.entries(tokens.layout)) add(k, v(node));

const css = `/* GENERATED by design/scripts/build-tokens.js from volve.tokens.json. Do not edit by hand. */
@font-face { font-family: "Inter"; font-weight: 100 900; font-display: swap; src: url("../fonts/inter-latin-var.woff2") format("woff2"); }
@font-face { font-family: "DM Serif Display"; font-weight: 400; font-style: normal; font-display: swap; src: url("../fonts/DMSerifDisplay-Regular.ttf") format("truetype"); }
@font-face { font-family: "DM Serif Display"; font-weight: 400; font-style: italic; font-display: swap; src: url("../fonts/DMSerifDisplay-Italic.ttf") format("truetype"); }

:root {
${lines.join('\n')}
}
`;

fs.writeFileSync(path.join(root, 'tokens', 'volve.css'), css);
console.log(`volve.css written (${lines.length} properties)`);
